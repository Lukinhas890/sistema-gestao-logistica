BEGIN;
CREATE TABLE IF NOT EXISTS motoristas (
 id UUID PRIMARY KEY, nome TEXT NOT NULL, cnh TEXT NOT NULL UNIQUE,
 telefone TEXT, ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS veiculos (
 id UUID PRIMARY KEY, placa TEXT NOT NULL UNIQUE, modelo TEXT NOT NULL,
 capacidade NUMERIC(14,2) NOT NULL CHECK (capacidade > 0), ativo BOOLEAN NOT NULL DEFAULT TRUE
);
COMMIT;
